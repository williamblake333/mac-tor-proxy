#!/bin/bash
# Mac Tor Proxy installer (mac-tor-proxy)
# A private Tor proxy for macOS plus a menu bar app that sends only the apps and
# scripts you choose through Tor.  https://github.com/williamblake333/mac-tor-proxy
#
#   Install / update:  bash install-mac-tor-proxy.sh
#   Uninstall:         bash install-mac-tor-proxy.sh --uninstall
#
# Installs with Homebrew: tor, proxychains-ng, python@3.13
# Creates:  ~/.mac-tor-proxy/                (app code, Python venv, Tor data, config, profiles)
#           ~/Applications/Mac Tor Proxy.app (double-click to open; lives in the menu bar)
#           ~/.mac-tor-proxy/bin/torrun      (CLI: torrun <command> runs it through Tor)
set -euo pipefail

REPO_RAW="https://raw.githubusercontent.com/williamblake333/mac-tor-proxy/main"
BASE="$HOME/.mac-tor-proxy"
APP="$HOME/Applications/Mac Tor Proxy.app"
PY_FORMULA="python@3.13"
ZSHRC="$HOME/.zshrc"
MARKER="# Mac Tor Proxy"

remove_path_line() {
  if [[ -f "$ZSHRC" ]] && grep -qF "$MARKER" "$ZSHRC"; then
    { grep -vF "$MARKER" "$ZSHRC" || true; } > "$ZSHRC.mtp-tmp"
    cat "$ZSHRC.mtp-tmp" > "$ZSHRC"
    rm -f "$ZSHRC.mtp-tmp"
  fi
}

if [[ "${1:-}" == "--uninstall" ]]; then
  echo "==> Quitting Mac Tor Proxy and its Tor instance"
  pkill -f "$BASE/mac_tor_proxy.py" 2>/dev/null || true
  if [[ -f "$BASE/tor.pid" ]]; then kill "$(cat "$BASE/tor.pid")" 2>/dev/null || true; fi
  rm -rf "$APP" "$BASE"
  remove_path_line
  echo "Mac Tor Proxy removed. The Homebrew packages are still installed; to remove them too:"
  echo "  brew uninstall tor proxychains-ng"
  exit 0
fi

if [[ "$(uname -s)" != "Darwin" ]]; then echo "Mac Tor Proxy is for macOS."; exit 1; fi

# Where this script lives (empty when piped from curl).
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" 2>/dev/null && pwd || true)"

echo "==> Checking Homebrew"
if ! command -v brew >/dev/null 2>&1; then
  if [[ -x /opt/homebrew/bin/brew ]]; then
    eval "$(/opt/homebrew/bin/brew shellenv)"
  elif [[ -x /usr/local/bin/brew ]]; then
    eval "$(/usr/local/bin/brew shellenv)"
  else
    echo "Homebrew isn't installed. Install it from https://brew.sh and run this script again."
    exit 1
  fi
fi

echo "==> Installing tor, proxychains-ng and $PY_FORMULA (already-installed ones are skipped)"
brew install tor proxychains-ng "$PY_FORMULA"
PY="$(brew --prefix "$PY_FORMULA")/bin/python3.13"

if brew services list 2>/dev/null | grep -Eq '^tor[[:space:]]+started'; then
  echo
  echo "NOTE: Homebrew's own Tor service is running and holds port 9050. Mac Tor Proxy runs its"
  echo "      own Tor on the same port, so stop the Homebrew one with:  brew services stop tor"
  echo
fi

echo "==> Setting up the Python environment (PySide6)"
mkdir -p "$BASE/bin"
chmod 700 "$BASE"
if [[ ! -x "$BASE/venv/bin/python" ]]; then
  "$PY" -m venv "$BASE/venv"
fi
"$BASE/venv/bin/python" -m pip install --quiet --upgrade pip
"$BASE/venv/bin/python" -m pip install --quiet --upgrade "PySide6-Essentials>=6.8"

echo "==> Installing the Mac Tor Proxy app"
pkill -f "$BASE/mac_tor_proxy.py" 2>/dev/null || true
NEW_APP="$BASE/mac_tor_proxy.py.new"
if [[ -n "$SCRIPT_DIR" && -f "$SCRIPT_DIR/mac_tor_proxy.py" ]]; then
  cp "$SCRIPT_DIR/mac_tor_proxy.py" "$NEW_APP"
else
  echo "    downloading mac_tor_proxy.py from GitHub"
  if ! curl -fsSL "$REPO_RAW/mac_tor_proxy.py" -o "$NEW_APP"; then
    echo "Couldn't download mac_tor_proxy.py. Clone the repository and run the installer from it:"
    echo "  git clone https://github.com/williamblake333/mac-tor-proxy.git ~/mac-tor-proxy"
    echo "  bash ~/mac-tor-proxy/install-mac-tor-proxy.sh"
    exit 1
  fi
fi
if ! "$BASE/venv/bin/python" -m py_compile "$NEW_APP" 2>/dev/null; then
  echo "mac_tor_proxy.py looks damaged or incomplete; not installing it."
  rm -f "$NEW_APP"
  exit 1
fi
mv "$NEW_APP" "$BASE/mac_tor_proxy.py"
rm -rf "$BASE/__pycache__"

cat > "$BASE/bin/torrun" <<'TORRUN'
#!/bin/bash
# torrun: run one command through Mac Tor Proxy's Tor (start Tor in Mac Tor Proxy first).
#   torrun curl https://check.torproject.org/api/ip     proxy env vars, for proxy-aware tools
#   torrun -p python3 my_script.py                      proxychains: forces all TCP (Homebrew binaries)
CFG="$HOME/.mac-tor-proxy/config.json"
SOCKS=$(plutil -extract socks_port raw -o - "$CFG" 2>/dev/null || echo 9050)
TUNNEL=$(plutil -extract http_tunnel_port raw -o - "$CFG" 2>/dev/null || echo 9080)
if [[ $# -eq 0 ]]; then sed -n '2,4p' "$0"; exit 1; fi
if [[ "$1" == "-p" ]]; then
  shift
  CONF="$HOME/.mac-tor-proxy/proxychains.conf"
  printf '# Generated by Mac Tor Proxy\nstrict_chain\nproxy_dns\nremote_dns_subnet 224\ntcp_read_time_out 15000\ntcp_connect_time_out 8000\nlocalnet 127.0.0.0/255.0.0.0\n[ProxyList]\nsocks5 127.0.0.1 %s\n' "$SOCKS" > "$CONF"
  exec proxychains4 -q -f "$CONF" "$@"
fi
S="socks5h://127.0.0.1:$SOCKS"; H="http://127.0.0.1:$TUNNEL"; N="localhost,127.0.0.1,::1"
export ALL_PROXY="$S" all_proxy="$S" HTTP_PROXY="$S" http_proxy="$S" HTTPS_PROXY="$H" https_proxy="$H"
export NO_PROXY="$N" no_proxy="$N" NODE_USE_ENV_PROXY=1 MAC_TOR_PROXY=1
exec "$@"
TORRUN
chmod +x "$BASE/bin/torrun"

echo "==> Creating $APP"
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
cat > "$APP/Contents/Info.plist" <<'PLIST'
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>Mac Tor Proxy</string>
  <key>CFBundleDisplayName</key><string>Mac Tor Proxy</string>
  <key>CFBundleIdentifier</key><string>io.github.williamblake333.mac-tor-proxy</string>
  <key>CFBundleExecutable</key><string>mac-tor-proxy</string>
  <key>CFBundleIconFile</key><string>AppIcon</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>1.0.0</string>
  <key>CFBundleVersion</key><string>1</string>
  <key>LSMinimumSystemVersion</key><string>13.0</string>
  <key>NSHighResolutionCapable</key><true/>
</dict>
</plist>
PLIST
cat > "$APP/Contents/MacOS/mac-tor-proxy" <<'LAUNCHER'
#!/bin/bash
exec "$HOME/.mac-tor-proxy/venv/bin/python" "$HOME/.mac-tor-proxy/mac_tor_proxy.py" >>"$HOME/.mac-tor-proxy/mac-tor-proxy.log" 2>&1
LAUNCHER
chmod +x "$APP/Contents/MacOS/mac-tor-proxy"
if "$BASE/venv/bin/python" "$BASE/mac_tor_proxy.py" --make-icon "$BASE/AppIcon.png" >/dev/null 2>&1 \
   && sips -s format icns "$BASE/AppIcon.png" --out "$APP/Contents/Resources/AppIcon.icns" >/dev/null 2>&1; then
  touch "$APP"
else
  echo "    (couldn't build the app icon; Mac Tor Proxy works fine without it)"
fi

if ! grep -qF "$MARKER" "$ZSHRC" 2>/dev/null; then
  echo 'export PATH="$HOME/.mac-tor-proxy/bin:$PATH"  # Mac Tor Proxy' >> "$ZSHRC"
fi

echo
echo "Mac Tor Proxy is installed and opening now."
echo "  App:  ~/Applications/Mac Tor Proxy.app  (onion icon in the menu bar while it runs)"
echo "  CLI:  open a new Terminal window, then:  torrun curl https://check.torproject.org/api/ip"
open "$APP"
